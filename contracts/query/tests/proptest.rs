// ── Constants ─────────────────────────────────────────────────────────────────

const INITIAL_TIMESTAMP: u64 = 1_000_000;
/// Liquidity pre-minted into the contract for draw tests.
const LIQUIDITY_AMOUNT: i128 = 100_000_000;
/// Maximum credit limit generated by strategies (keeps test fast).
const MAX_CREDIT_LIMIT: i128 = 500_000;
/// Maximum draw amount in draw-based strategies.
const MAX_DRAW: i128 = 100_000;

// ── Setup helpers ─────────────────────────────────────────────────────────────

/// Create a minimal test environment with a Credit contract and admin.
///
/// Returns `(env, client, admin)` ready for non-draw tests that do not
/// require a liquidity token.
fn setup_env() -> (Env, CreditClient<'static>, Address) {
    let env = Env::default();
    env.mock_all_auths();
    env.ledger().set_timestamp(INITIAL_TIMESTAMP);

    let admin = Address::generate(&env);
    let contract_id = env.register(Credit, ());
    let client = CreditClient::new(&env, &contract_id);
    client.init(&admin);

    (env, client, admin)
}

/// Create a test environment with a liquidity token pre-minted so that
/// `draw_credit` calls succeed.
///
/// Returns `(env, client, contract_id, admin)`.
fn setup_with_token() -> (Env, CreditClient<'static>, Address, Address) {
    let env = Env::default();
    env.mock_all_auths();
    env.ledger().set_timestamp(INITIAL_TIMESTAMP);

    let admin = Address::generate(&env);
    let contract_id = env.register(Credit, ());
    let client = CreditClient::new(&env, &contract_id);
    client.init(&admin);

    // Register and configure liquidity token.
    let token_id = env.register_stellar_asset_contract_v2(Address::generate(&env));
    let token = token_id.address();
    client.set_liquidity_token(&token);
    client.set_liquidity_source(&contract_id);
    // Disable collateral requirement so draws succeed unconditionally.
    client.set_min_collateral_ratio_bps(&0);

    StellarAssetClient::new(&env, &token).mint(&contract_id, &LIQUIDITY_AMOUNT);

    (env, client, contract_id, admin)
}

// ── Invariant assertion helpers ───────────────────────────────────────────────

/// Assert `get_protocol_summary().count >= 0` and
/// `get_protocol_summary().total_utilized >= 0`.
fn assert_protocol_summary_non_negative(client: &CreditClient<'_>, label: &str) {
    let summary = client.get_protocol_summary();
    assert!(
        summary.total_utilized >= 0,
        "{label}: total_utilized is negative: {}",
        summary.total_utilized,
    );
    // count is u32 so it is always >= 0 by type; just document the check.
    let _ = summary.count;
}

/// Assert that `delinquency_applicable = false` implies `is_delinquent = false`.
fn assert_delinquency_gate(client: &CreditClient<'_>, borrower: &Address, label: &str) {
    let caps = client.query_capabilities(borrower);
    if !caps.delinquency_applicable {
        assert!(
            !caps.is_delinquent,
            "{label}: is_delinquent must be false when delinquency_applicable is false",
        );
    }
}

/// Assert that `health_factor_applicable = false` implies `get_health_factor`
/// returns `u32::MAX`.
fn assert_health_factor_sentinel(client: &CreditClient<'_>, borrower: &Address, label: &str) {
    let caps = client.query_capabilities(borrower);
    if !caps.health_factor_applicable {
        let hf = client.get_health_factor(borrower);
        assert_eq!(
            hf,
            u32::MAX,
            "{label}: health_factor must be u32::MAX when not applicable, got {hf}",
        );
    }
}

// ── Strategies ────────────────────────────────────────────────────────────────

/// Generate a valid `(credit_limit, interest_rate_bps, risk_score)` triple.
///
/// - `credit_limit`: 1 .. MAX_CREDIT_LIMIT
/// - `interest_rate_bps`: 1 .. 10_000
/// - `risk_score`: 0 .. 100
fn credit_line_params() -> impl Strategy<Value = (i128, u32, u32)> {
    (
        1_i128..=MAX_CREDIT_LIMIT,
        1_u32..=10_000_u32,
        0_u32..=100_u32,
    )
}

/// Generate a valid draw amount in `1 .. limit`.
fn draw_amount(limit: i128) -> impl Strategy<Value = i128> {
    1_i128..=limit.min(MAX_DRAW).max(1)
}

/// Generate a valid `(amount_per_period, period_seconds, next_due_ts)` schedule.
///
/// - `amount_per_period`: 1 .. 10_000
/// - `period_seconds`: 3600 .. 2_592_000 (1 hour to 30 days)
/// - `next_due_ts`: INITIAL_TIMESTAMP .. INITIAL_TIMESTAMP + 7_776_000 (90 days)
fn schedule_params() -> impl Strategy<Value = (i128, u64, u64)> {
    (
        1_i128..=10_000_i128,
        3_600_u64..=2_592_000_u64,
        INITIAL_TIMESTAMP..=(INITIAL_TIMESTAMP + 7_776_000_u64),
    )
}

// ═══════════════════════════════════════════════════════════════════════════
// Proptest 1 — Capabilities bitmap consistency: no credit line → all false
// ═══════════════════════════════════════════════════════════════════════════

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **Invariant**: When a borrower has no credit line, every field in
    /// [`QueryCapabilities`] must be `false`, regardless of the address value.
    ///
    /// This covers the "unknown borrower" short-circuit at the top of the
    /// `capabilities()` view.
    #[test]
    fn prop_no_credit_line_all_capabilities_false(
        // Use the raw bytes to vary the generated address — we ignore this
        // value directly but it forces proptest to generate different envs.
        _seed in 0u64..u64::MAX,
    ) {
        let (env, client, _admin) = setup_env();
        let borrower = Address::generate(&env);

        let caps = client.query_capabilities(&borrower);

        prop_assert!(
            !caps.has_credit_line,
            "no line → has_credit_line must be false",
        );
        prop_assert!(
            !caps.has_repayment_schedule,
            "no line → has_repayment_schedule must be false",
        );
        prop_assert!(
            !caps.health_factor_applicable,
            "no line → health_factor_applicable must be false",
        );
        prop_assert!(
            !caps.delinquency_applicable,
            "no line → delinquency_applicable must be false",
        );
        prop_assert!(
            !caps.is_delinquent,
            "no line → is_delinquent must be false",
        );

        // Confirm health_factor returns u32::MAX for unknown borrowers.
        let hf = client.get_health_factor(&borrower);
        prop_assert_eq!(
            hf,
            u32::MAX,
            "no line → get_health_factor must return u32::MAX, got {hf}",
        );

        // Confirm is_delinquent returns false for unknown borrowers.
        let delinquent = client.is_delinquent(&borrower);
        prop_assert!(
            !delinquent,
            "no line → is_delinquent must be false",
        );
    }
}

// ═══════════════════════════════════════════════════════════════════════════
// Proptest 2 — Capabilities bitmap with open line, zero utilization
// ═══════════════════════════════════════════════════════════════════════════

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **Invariant**: An open line with zero utilization must have:
    /// - `has_credit_line = true`
    /// - `health_factor_applicable = false` (zero debt)
    /// - `delinquency_applicable = false` (zero debt)
    /// - `is_delinquent = false`
    /// - `get_health_factor` returns `u32::MAX`
    ///
    /// `has_repayment_schedule` follows whether a schedule was configured;
    /// but `delinquency_applicable` stays false because utilization is zero.
    #[test]
    fn prop_open_line_zero_utilization_capabilities(
        (limit, rate, score) in credit_line_params(),
    ) {
        let (env, client, _admin) = setup_env();
        let borrower = Address::generate(&env);
        client.open_credit_line(&borrower, &limit, &rate, &score);

        let caps = client.query_capabilities(&borrower);

        prop_assert!(caps.has_credit_line, "open line → has_credit_line must be true");
        prop_assert!(
            !caps.health_factor_applicable,
            "zero utilization → health_factor_applicable must be false",
        );
        prop_assert!(
            !caps.delinquency_applicable,
            "zero utilization → delinquency_applicable must be false",
        );
        prop_assert!(!caps.is_delinquent, "zero utilization → is_delinquent must be false");

        // Confirm health_factor returns u32::MAX.
        let hf = client.get_health_factor(&borrower);
        prop_assert_eq!(
            hf,
            u32::MAX,
            "zero utilization → get_health_factor must return u32::MAX, got {hf}",
        );

        // delinquency_applicable → is_delinquent gate.
        assert_delinquency_gate(&client, &borrower, "zero_util");
        assert_health_factor_sentinel(&client, &borrower, "zero_util");
    }
}

