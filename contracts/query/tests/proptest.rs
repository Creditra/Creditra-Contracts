// ═══════════════════════════════════════════════════════════════════════════
// Proptest 10 — delinquency_applicable gate: is_delinquent ≤ delinquency_applicable
// ═══════════════════════════════════════════════════════════════════════════

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **Invariant**: `is_delinquent` can only be `true` when
    /// `delinquency_applicable` is also `true`.  That is, the gate
    /// `delinquency_applicable → is_delinquent` must hold in both directions:
    ///
    /// ```text
    /// ¬delinquency_applicable ⟹ ¬is_delinquent
    /// ```
    ///
    /// Tested with arbitrary line configurations (with and without schedule,
    /// with and without utilization) to ensure the implication is universal.
    #[test]
    fn prop_delinquency_gate_implication(
        (limit, rate, score) in credit_line_params(),
        (amt_per_period, period_secs, next_due_ts) in schedule_params(),
        attach_schedule in proptest::bool::ANY,
        time_advance in 0u64..=15_552_000u64,
    ) {
        let (env, client, _contract_id, _admin) = setup_with_token();
        let borrower = Address::generate(&env);
        client.open_credit_line(&borrower, &limit, &rate, &score);

        if attach_schedule {
            client.set_repayment_schedule(
                &borrower,
                &amt_per_period,
                &period_secs,
                &next_due_ts,
            );
        }

        // Draw a fraction of the limit to get non-zero utilization.
        let draw = (limit / 3).max(1).min(MAX_DRAW);
        let _ = client.try_draw_credit(&borrower, &draw);

        // Advance time to potentially pass due date.
        env.ledger().with_mut(|l| l.timestamp += time_advance);

        let caps = client.query_capabilities(&borrower);

        // Core implication: ¬applicable ⟹ ¬delinquent.
        if !caps.delinquency_applicable {
            prop_assert!(
                !caps.is_delinquent,
                "¬delinquency_applicable ⟹ ¬is_delinquent must hold \
                 (attach_schedule={attach_schedule}, time_advance={time_advance}s)",
            );
        }

        // Also verify consistency between capability bitmap and direct call.
        let direct = client.is_delinquent(&borrower);
        prop_assert_eq!(
            caps.is_delinquent,
            direct,
            "caps.is_delinquent must match direct is_delinquent() call",
        );
    }
}

