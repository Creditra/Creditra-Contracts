//! Property-based tests for query (v7) state invariants.
//!
//! # What
//!
//! Generates random credit-line configurations, utilization levels, and
//! repayment schedule parameters, then verifies that key query-subsystem
//! invariants hold for every generated input.
//!
//! # Invariants
//!
//! 1. **Capabilities bitmap consistency**: Every field in [`QueryCapabilities`]
//!    is derived deterministically from storage state. The same borrower
//!    address always yields the same bitmap when the underlying state has not
//!    changed.
//! 2. **`query_capabilities` determinism**: Consecutive calls with the same
//!    borrower and unchanged state must return identical bitmaps.
//! 3. **Health-factor sentinel**: `get_health_factor` returns `u32::MAX` when
//!    `utilized_amount == 0`; it returns a finite value when
//!    `utilized_amount > 0`.
//! 4. **`is_delinquent` short-circuit**: `is_delinquent` must return `false`
//!    when there is no credit line, the line is `Closed`, `utilized_amount`
//!    is zero, or there is no repayment schedule.
//! 5. **`get_protocol_summary` non-negative**: `count` and `total_utilized`
//!    returned by `get_protocol_summary` are never negative after any sequence
//!    of open/draw/repay operations.
//! 6. **`get_credit_line` idempotency**: A pure read must return the same
//!    value on two consecutive calls when no state mutation occurs between
//!    them.
//!
//! # Covered paths
//!
//! | Path                     | Why it matters                                    |
//! |--------------------------|---------------------------------------------------|
//! | `query_capabilities`     | Bitmap correctness across all state configurations|
//! | `get_credit_line`        | Idempotent read; consistent with capabilities     |
//! | `get_health_factor`      | Sentinel (`u32::MAX`) for zero debt; finite value |
//! | `is_delinquent`          | Short-circuit paths and schedule interaction      |
//! | `get_protocol_summary`   | Aggregate non-negativity after mutations          |
//! | `set_repayment_schedule` | Schedule presence drives delinquency_applicable   |
//!
//! # See also
//!
//! - `contracts/query/tests/capabilities.rs` — deterministic capabilities tests.
//! - `contracts/query/tests/rustdoc_query_tests.rs` — rustdoc coverage tests.
//! - `contracts/accrual/tests/proptest.rs` — accrual invariant proptest pattern.
//! - `contracts/risk/tests/proptest.rs` — risk invariant proptest pattern.

